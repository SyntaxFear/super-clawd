export const GLYPH_W = 5;
export const GLYPH_H = 8;
export const ADVANCE = 6;

const CHARS = Object.keys(GLYPHS);
const INDEX = new Map<string, number>(CHARS.map((c, i) => [c, i]));

export function glyphIndex(ch: string): number {
  return INDEX.get(ch) ?? INDEX.get('?')!;
}

const atlases = new Map<string, Img>();

function atlas(color: string): Img {
  let a = atlases.get(color);
  if (a) return a;
  a = canvas(CHARS.length * ADVANCE, GLYPH_H);
  const g = ctx2d(a);
  g.fillStyle = color;
  CHARS.forEach((ch, i) => {
    const rows = GLYPHS[ch] ? GLYPHS[ch].split('|') : [];
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') g.fillRect(i * ADVANCE + x, y, 1, 1);
    });
  });
  atlases.set(color, a);
  return a;
}

export function measure(text: string, scale = 1): number {
  const n = Array.from(text).length;
  return n ? (n * ADVANCE - 1) * scale : 0;
}

export interface TextOpts {
  scale?: number;
  align?: 'left' | 'center' | 'right';
  shadow?: string;
  outline?: string;
  alpha?: number;
}

function blit(g: CanvasRenderingContext2D, chars: string[], x: number, y: number, color: string, s: number): void {
  const a = atlas(color);
  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i];
    if (ch === ' ') continue;
    const gi = glyphIndex(ch);
    g.drawImage(a, gi * ADVANCE, 0, GLYPH_W, GLYPH_H, x + i * ADVANCE * s, y, GLYPH_W * s, GLYPH_H * s);
  }
}

/** Draw pixel text. Returns the drawn width. */
export function drawText(g: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, opts: TextOpts = {}): number {
  const s = opts.scale ?? 1;
  const chars = Array.from(text);
  const w = measure(text, s);
  let x0 = opts.align === 'center' ? x - w / 2 : opts.align === 'right' ? x - w : x;
  x0 = Math.round(x0);
  const y0 = Math.round(y);
  const prevAlpha = g.globalAlpha;
  if (opts.alpha !== undefined) g.globalAlpha = prevAlpha * opts.alpha;
  if (opts.outline) {
    for (let oy = -1; oy <= 1; oy++)
      for (let ox = -1; ox <= 1; ox++) if (ox || oy) blit(g, chars, x0 + ox * s, y0 + oy * s, opts.outline, s);
  }
  if (opts.shadow) blit(g, chars, x0 + s, y0 + s, opts.shadow, s);
  blit(g, chars, x0, y0, color, s);
  g.globalAlpha = prevAlpha;
  return w;
}
